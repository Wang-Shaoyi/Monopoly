export function translate(lang: Lang, text: string, mapId: MapId = 'china'): string {
  if (lang !== 'en' || !text) return text
  const exact = EXACT[text]
  if (exact) return exact
  const rent = text.match(/^(.+)租金$/)
  if (rent) {
    const space = spacesForMap(mapId).find((item) => item.name === rent[1])
    return `${space?.en ?? rent[1]} rent`
  }
  const taken = text.match(/^该角色已被 (.+) 选中$/)
  if (taken) return `This character has already been chosen by ${taken[1]}.`
  const cash = text.match(/^(.+) 的现金不够$/)
  if (cash) return `${cash[1]} does not have enough cash`
  const interest = text.match(/^(.+) 接手抵押地需要先付利息 \$(\d+)$/)
  if (interest) return `${interest[1]} must pay $${interest[2]} in interest to take over a mortgaged property`
  const place = spacesForMap(mapId).find((item) => item.name === text)
  if (place) return place.en
  return text
}
