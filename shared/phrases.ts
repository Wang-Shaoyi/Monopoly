export function translate(lang: Lang, text: string): string {
  if (lang !== 'en' || !text) return text
  const exact = EXACT[text]
  if (exact) return exact
  const rent = text.match(/^(.+)租金$/)
  if (rent) {
    const space = SPACES.find((item) => item.name === rent[1])
    return `${space?.en ?? rent[1]} rent`
  }
  const cash = text.match(/^(.+) 的现金不够$/)
  if (cash) return `${cash[1]} does not have enough cash`
  const interest = text.match(/^(.+) 接手抵押地需要先付利息 \$(\d+)$/)
  if (interest) return `${interest[1]} must pay $${interest[2]} interest to take a mortgaged lot`
  const place = SPACES.find((item) => item.name === text)
  if (place) return place.en
  return text
}
